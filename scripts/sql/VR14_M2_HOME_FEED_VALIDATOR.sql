USE south_stand;
SET NAMES utf8mb4;

SELECT 'vr14_m2_target_rows' metric, COUNT(*) value
FROM content
WHERE ((id BETWEEN 16000000000000001 AND 16000000000000120 AND hot_score BETWEEN 0.00 AND 20.00)
    OR (id BETWEEN 16000000000000201 AND 16000000000000210 AND hot_score BETWEEN 121.00 AND 130.00)
    OR (id BETWEEN 16000000000000901 AND 16000000000000912 AND hot_score BETWEEN 0.00 AND 14.00)
    OR (id BETWEEN 20001 AND 20006 AND hot_score BETWEEN 0.00 AND 5.00))
  AND status='PUBLISHED' AND is_deleted=0;

SELECT 'vr14_m2_expected_target_rows' metric,
       CASE WHEN COUNT(*)=144 THEN 144 ELSE COUNT(*) END value
FROM content
WHERE status='PUBLISHED' AND is_deleted=0
  AND ((id BETWEEN 16000000000000001 AND 16000000000000120
       AND author_id BETWEEN 11000000000000001 AND 11000000000000035
       AND source_type='USER')
   OR (id BETWEEN 16000000000000201 AND 16000000000000210
       AND author_id BETWEEN 11000000000000001 AND 11000000000000010
       AND source_type='USER' AND remark='P1_M3_DEMO_CONTENT')
   OR (id BETWEEN 16000000000000901 AND 16000000000000912
       AND author_id IN (10002,11000000000000016)
       AND source_type='USER' AND remark='VR9_R1_DEMO_CONTENT')
   OR (id BETWEEN 20001 AND 20006 AND author_id IN (10001,10002)));

SELECT 'vr14_m2_target_ownership_invalid' metric, COUNT(*) value
FROM content
WHERE ((id BETWEEN 16000000000000001 AND 16000000000000120
        AND NOT (author_id BETWEEN 11000000000000001 AND 11000000000000035
                AND source_type='USER'))
    OR (id BETWEEN 16000000000000201 AND 16000000000000210
        AND NOT (author_id BETWEEN 11000000000000001 AND 11000000000000010
                AND source_type='USER' AND remark='P1_M3_DEMO_CONTENT'))
    OR (id BETWEEN 16000000000000901 AND 16000000000000912
        AND NOT (author_id IN (10002,11000000000000016)
                AND source_type='USER' AND remark='VR9_R1_DEMO_CONTENT'))
    OR (id BETWEEN 20001 AND 20006
        AND NOT (author_id IN (10001,10002)
                AND source_type IN ('ADMIN','USER'))));

SELECT 'vr14_m2_target_rows_invalid' metric, COUNT(*) value
FROM content
WHERE ((id BETWEEN 16000000000000001 AND 16000000000000120 AND (hot_score < 0.00 OR hot_score > 20.00))
    OR (id BETWEEN 16000000000000201 AND 16000000000000210 AND (hot_score < 121.00 OR hot_score > 130.00))
    OR (id BETWEEN 16000000000000901 AND 16000000000000912 AND (hot_score < 0.00 OR hot_score > 14.00))
    OR (id BETWEEN 20001 AND 20006 AND (hot_score < 0.00 OR hot_score > 5.00)))
  AND status='PUBLISHED' AND is_deleted=0;
